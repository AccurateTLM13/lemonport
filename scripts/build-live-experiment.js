const fs = require("node:fs");
const path = require("node:path");
const { assertSafePublicUrl, assertSafeRelativeAssetPath, hasText } = require("./security-utils");

const root = path.resolve(__dirname, "..");
const contentFile = path.join(root, "content", "live-experiment.json");
const outputFile = path.join(root, "assets", "js", "live-experiment-data.js");

function assertArray(value, label) {
  if (!Array.isArray(value)) {
    throw new Error(`${label} must be an array.`);
  }
}

function validateLinkField(value, label, errors, options = {}) {
  try {
    assertSafePublicUrl(value, label, options);
  } catch (error) {
    errors.push(error.message);
  }
}

function validateLiveExperiment(data) {
  const errors = [];

  if (!data || typeof data !== "object") {
    errors.push("Live experiment content must be an object.");
    return { errors };
  }

  if (!data.hero || typeof data.hero !== "object") {
    errors.push("hero is required.");
  } else {
    ["kicker", "headline", "subheadline", "intro"].forEach((field) => {
      if (!hasText(data.hero[field])) {
        errors.push(`hero.${field} is required.`);
      }
    });
    try {
      assertArray(data.hero.actions, "hero.actions");
      assertArray(data.hero.metadata, "hero.metadata");
    } catch (error) {
      errors.push(error.message);
    }

    (data.hero.actions || []).forEach((action, index) => {
      validateLinkField(action && action.href, `hero.actions[${index}].href`, errors, { allowEmpty: true });
    });
  }

  if (!data.ledger || typeof data.ledger !== "object") {
    errors.push("ledger is required.");
  } else {
    ["title", "report"].forEach((field) => {
      if (!hasText(data.ledger[field])) {
        errors.push(`ledger.${field} is required.`);
      }
    });
    try {
      assertArray(data.ledger.rows, "ledger.rows");
    } catch (error) {
      errors.push(error.message);
    }
  }

  if (!data.buildLog || typeof data.buildLog !== "object") {
    errors.push("buildLog is required.");
  } else {
    try {
      assertArray(data.buildLog.entries, "buildLog.entries");
    } catch (error) {
      errors.push(error.message);
    }

    if (data.buildLog.button && data.buildLog.button.href) {
      validateLinkField(data.buildLog.button.href, "buildLog.button.href", errors, { allowEmpty: true });
    }
  }

  if (!data.currentBet || typeof data.currentBet !== "object") {
    errors.push("currentBet is required.");
  } else if (!hasText(data.currentBet.title)) {
    errors.push("currentBet.title is required.");
  } else if (data.currentBet.button && data.currentBet.button.href) {
    validateLinkField(data.currentBet.button.href, "currentBet.button.href", errors, { allowEmpty: true });
  }

  if (!data.getInvolved || typeof data.getInvolved !== "object") {
    errors.push("getInvolved is required.");
  } else {
    try {
      assertArray(data.getInvolved.items, "getInvolved.items");
    } catch (error) {
      errors.push(error.message);
    }

    if (data.getInvolved.button && data.getInvolved.button.href) {
      validateLinkField(data.getInvolved.button.href, "getInvolved.button.href", errors, { allowEmpty: true });
    }

    (data.getInvolved.items || []).forEach((item, index) => {
      validateLinkField(item && item.href, `getInvolved.items[${index}].href`, errors, { allowEmpty: true });
    });
  }

  if (data.assets && data.assets.mascot) {
    try {
      assertSafeRelativeAssetPath(data.assets.mascot, "assets.mascot");
    } catch (error) {
      errors.push(error.message);
    }
  }

  return { errors };
}

function loadLiveExperiment() {
  return JSON.parse(fs.readFileSync(contentFile, "utf8"));
}

function buildLiveExperiment() {
  const data = loadLiveExperiment();
  const result = validateLiveExperiment(data);

  if (result.errors.length) {
    const error = new Error(`Live experiment validation failed:\n- ${result.errors.join("\n- ")}`);
    error.validation = result;
    throw error;
  }

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(
    outputFile,
    `/* Generated by scripts/build-live-experiment.js. Do not edit directly; update content/live-experiment.json and rebuild. */\nwindow.liveExperimentData = ${JSON.stringify(data, null, 2)};\n`
  );

  return { outputFile, data };
}

if (require.main === module) {
  const result = buildLiveExperiment();
  console.log(`Built ${path.relative(root, result.outputFile).replace(/\\/g, "/")}`);
}

module.exports = {
  contentFile,
  outputFile,
  loadLiveExperiment,
  validateLiveExperiment,
  buildLiveExperiment
};
