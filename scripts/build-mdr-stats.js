const fs = require("node:fs");
const path = require("node:path");
const { loadMdr } = require("./build-mdr");

const root = path.resolve(__dirname, "..");
const outputFile = path.join(root, "assets", "js", "mdr-stats.js");

async function fetchStats(apiBase) {
  const response = await fetch(`${apiBase.replace(/\/$/, "")}/stats`);

  if (!response.ok) {
    throw new Error(`Stats request failed with ${response.status}.`);
  }

  return response.json();
}

async function buildMdrStats() {
  const config = loadMdr();
  const apiBase = String(process.env.MDR_API_BASE || config.apiBase || "").trim();
  let stats;

  if (apiBase) {
    stats = await fetchStats(apiBase);
  } else {
    stats = {
      totalCents: config.mockStats.totalCents,
      count: config.mockStats.count,
      remaining: config.mockStats.remaining,
      recent: config.mockReceipts.slice(0, 20),
      source: "mock"
    };
  }

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(
    outputFile,
    `/* Generated by scripts/build-mdr-stats.js. Do not edit directly. */\nwindow.mdrStats = ${JSON.stringify(stats, null, 2)};\n`
  );

  return { outputFile, stats };
}

if (require.main === module) {
  buildMdrStats()
    .then((result) => {
      console.log(`Built ${path.relative(root, result.outputFile).replace(/\\/g, "/")}`);
    })
    .catch((error) => {
      console.error(error.message);
      process.exitCode = 1;
    });
}

module.exports = {
  outputFile,
  buildMdrStats
};
