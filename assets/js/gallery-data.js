window.galleryItems = galleryItems;

function normalizeGalleryValue(value) {
  return String(value || "").trim().toLowerCase();
}

function galleryCategoryMatches(item, category) {
  const requested = normalizeGalleryValue(category);

  if (!requested || requested === "all") {
    return true;
  }

  return normalizeGalleryValue(item.categorySlug) === requested
    || normalizeGalleryValue(item.category) === requested
    || normalizeGalleryValue(item.categoryLabel) === requested;
}

function getItemById(id) {
  return galleryItems.find((item) => item.id === id) || null;
}

function getItemsByCategory(category) {
  return galleryItems.filter((item) => galleryCategoryMatches(item, category));
}

function getItemsByTag(tag) {
  const requested = normalizeGalleryValue(tag);
  return galleryItems.filter((item) => Array.isArray(item.tags) && item.tags.some((itemTag) => normalizeGalleryValue(itemTag) === requested));
}

function getFeaturedItems() {
  return galleryItems.filter((item) => item.featured === true);
}

function getRelatedItems(id) {
  const item = getItemById(id);

  if (!item || !Array.isArray(item.related)) {
    return [];
  }

  return item.related.map(getItemById).filter(Boolean);
}

window.getItemById = getItemById;
window.getItemsByCategory = getItemsByCategory;
window.getItemsByTag = getItemsByTag;
window.getFeaturedItems = getFeaturedItems;
window.getRelatedItems = getRelatedItems;
window.galleryHelpers = {
  getItemById,
  getItemsByCategory,
  getItemsByTag,
  getFeaturedItems,
  getRelatedItems
};
